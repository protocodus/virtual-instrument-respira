// Tunes every reed of the instrument offline and writes Source/DSP/ReedTuning.h:
// for each push and pull tongue, the ratio of its natural frequency to the
// pitch it must sound at kTuningPressure, found by simulating it in its chamber.
// The engine builds reeds from this table at note-on, so tuning never runs on
// the audio thread.
//
//   GenerateReedTuning <ReedTuning.h>           write the table
//   GenerateReedTuning --check <ReedTuning.h>   fail unless the committed table
//                                               matches a fresh tuning
#include "ReedProbe.h"

#include <atomic>
#include <cmath>
#include <cstdio>
#include <cstring>
#include <fstream>
#include <sstream>
#include <string>
#include <thread>
#include <vector>

namespace {

using namespace respira;

struct Entry {
    int rank, key;
    std::array<double, 2> ratios {};
};

std::vector<Entry> Tune() {
    std::vector<Entry> entries;
    for (int rank = 0; rank < kRankCount; ++rank) {
        if (IsTreble(rank))
            for (int key = kTrebleLow; key <= kTrebleHigh; ++key) entries.push_back({ rank, key });
        else
            for (int pc = 0; pc < 12; ++pc) entries.push_back({ rank, pc });
    }
    std::atomic<std::size_t> next { 0 };
    std::vector<std::thread> workers;
    const unsigned count = std::max(1u, std::thread::hardware_concurrency());
    for (unsigned w = 0; w < count; ++w)
        workers.emplace_back([&] {
            for (std::size_t i; (i = next++) < entries.size();)
                entries[i].ratios = probe::TuneCell(entries[i].rank, entries[i].key);
        });
    for (auto& w : workers) w.join();
    return entries;
}

std::string Header(const std::vector<Entry>& entries) {
    std::ostringstream out;
    out << "#pragma once\n\n"
           "// Generated by Tools/GenerateReedTuning.cpp; change the reed model and regenerate,\n"
           "// never edit by hand. natural / wanted frequency of each reed's push [0] and pull [1]\n"
           "// tongue at kTuningPressure: treble ranks by key - kTrebleLow, bass-side ranks by\n"
           "// pitch class.\n\n"
           "#include \"ReedBank.h\"\n\n"
           "namespace respira {\n\n"
           "inline constexpr float kReedTuning[kRankCount][kTrebleKeys][2] = {\n";
    int rank = -1;
    for (const Entry& e : entries) {
        if (e.rank != rank) {
            if (rank >= 0) out << "    },\n";
            rank = e.rank;
            out << "    {\n";
        }
        char line[96];
        std::snprintf(line, sizeof line, "        { %.8ff, %.8ff },\n", e.ratios[0], e.ratios[1]);
        out << line;
    }
    out << "    },\n};\n\n} // namespace respira\n";
    return out.str();
}

std::vector<double> Numbers(const std::string& text) {
    std::vector<double> values;
    const std::size_t start = text.find("= {");
    for (std::size_t i = start; i != std::string::npos && i < text.size(); ++i) {
        if ((text[i] >= '0' && text[i] <= '9') || text[i] == '-') {
            char* end = nullptr;
            values.push_back(std::strtod(text.c_str() + i, &end));
            i = static_cast<std::size_t>(end - text.c_str());
        }
    }
    return values;
}

} // namespace

int main(int argc, char** argv) {
    const bool check = argc == 3 && std::strcmp(argv[1], "--check") == 0;
    if (argc != 2 && !check) {
        std::fprintf(stderr, "usage: GenerateReedTuning [--check] <ReedTuning.h>\n");
        return 2;
    }
    const char* path = argv[argc - 1];
    const std::string fresh = Header(Tune());
    if (!check) {
        std::ofstream(path, std::ios::binary) << fresh;
        std::printf("wrote %s\n", path);
        return 0;
    }
    std::ifstream file(path, std::ios::binary);
    std::stringstream committed;
    committed << file.rdbuf();
    const auto want = Numbers(fresh), have = Numbers(committed.str());
    if (want.size() != have.size()) {
        std::printf("FAIL %s holds %zu ratios, a fresh tuning %zu\n", path, have.size(), want.size());
        return 1;
    }
    // Another compiler or libm may round the simulation differently; a ratio
    // off by 3e-6 is 0.005 cents.
    std::size_t worst = 0;
    for (std::size_t i = 0; i < want.size(); ++i)
        if (std::fabs(have[i] - want[i]) > std::fabs(have[worst] - want[worst])) worst = i;
    const double error = std::fabs(have[worst] - want[worst]);
    std::printf("%s %zu ratios, largest difference %.2g\n", error <= 3.0e-6 ? "PASS" : "FAIL", want.size(), error);
    return error <= 3.0e-6 ? 0 : 1;
}
